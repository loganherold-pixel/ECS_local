#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const DEFAULT_SOURCE = path.join(
  process.env.TEMP || process.env.TMP || '',
  'ecoflow-ble-research',
  'ha-ef-ble',
  'custom_components',
  'ef_ble',
  'eflib',
  'keydata.py',
);
const DEFAULT_OUTPUT = path.join(process.cwd(), 'lib', 'ecoflowBleKeyData.ts');

function extractKeyDataBase64(sourcePath) {
  const source = fs.readFileSync(sourcePath, 'utf8');
  const match = source.match(/_data\s*=\s*base64\.b64decode\(\s*b"\\([\s\S]*?)"\s*\)/);
  if (!match) throw new Error(`Unable to extract EcoFlow BLE key data from ${sourcePath}`);
  return match[1].replace(/\\\r?\n/g, '').replace(/\s+/g, '');
}

function writeKeyDataModule(outputPath, base64) {
  const content = [
    '// Generated by scripts/extract-ecoflow-ble-keydata.js.',
    '// Static EcoFlow BLE session-key lookup data used for local type-7 diagnostic handshakes.',
    '',
    `export const ECOFLOW_BLE_KEY_DATA_BASE64 = '${base64}';`,
    '',
  ].join('\n');
  fs.writeFileSync(outputPath, content, 'utf8');
}

function main() {
  const sourcePath = process.argv[2] || DEFAULT_SOURCE;
  const outputPath = process.argv[3] || DEFAULT_OUTPUT;
  const base64 = extractKeyDataBase64(sourcePath);
  writeKeyDataModule(outputPath, base64);
  console.log(`[EcoFlow BLE KeyData] wrote ${outputPath} (${base64.length} base64 chars)`);
}

if (require.main === module) {
  main();
}

module.exports = {
  extractKeyDataBase64,
};
